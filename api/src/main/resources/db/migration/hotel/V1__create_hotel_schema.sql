CREATE TABLE hotel.hotel (
    hotel_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      VARCHAR(100)   NOT NULL,
    address   VARCHAR(250)   NOT NULL,
    latitude  DECIMAL(10, 7) NOT NULL,
    longitude DECIMAL(10, 7) NOT NULL
);

CREATE TABLE hotel.room (
    room_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    floor        INT          NOT NULL,
    number       INT          NOT NULL,
    hotel_id     BIGINT       NOT NULL,
    name         VARCHAR(100) NOT NULL,
    is_available BOOLEAN      NOT NULL,
    CONSTRAINT fk_room_hotel FOREIGN KEY (hotel_id) REFERENCES hotel.hotel (hotel_id) ON DELETE CASCADE
);

CREATE TABLE hotel.room_type_rate (
    hotel_id BIGINT         NOT NULL,
    date     DATE           NOT NULL,
    rate     DECIMAL(19, 2) NOT NULL
);
