CREATE TABLE reservation.guest (
    guest_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(100) NOT NULL,
    last_name  VARCHAR(100) NOT NULL,
    email      VARCHAR(100) NOT NULL
);

-- hotel_id is a plain reference to the hotel module: no foreign key across schemas
CREATE TABLE reservation.room_type_inventory (
    hotel_id        BIGINT NOT NULL,
    room_type_id    BIGINT NOT NULL,
    date            DATE   NOT NULL,
    total_inventory INT    NOT NULL,
    total_reserved  INT    NOT NULL,
    CONSTRAINT pk_room_type_inventory PRIMARY KEY (hotel_id, room_type_id, date)
);

CREATE TABLE reservation.reservation (
    reservation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id       BIGINT      NOT NULL,
    room_type_id   BIGINT      NOT NULL,
    start_date     DATE        NOT NULL,
    end_date       DATE        NOT NULL,
    status         VARCHAR(20) NOT NULL,
    guest_id       BIGINT      NOT NULL,
    CONSTRAINT fk_reservation_guest FOREIGN KEY (guest_id) REFERENCES reservation.guest (guest_id) ON DELETE CASCADE
);
